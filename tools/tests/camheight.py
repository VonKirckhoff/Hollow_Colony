# Camera height: + and − in 2D (scale, the middle stays put, mouse → map, saved) and in 3D (camera distance, saved), 0 resets.
from playwright.sync_api import sync_playwright
errs=[]; ok=True
J=lambda pg,s: pg.evaluate(s)
def check(n,c,v=''):
    global ok; print(n,'OK' if c else 'FAIL',v); ok&=bool(c)
def start(pg):
    pg.goto('file:///home/claude/hollow_colony/index.html'); pg.wait_for_timeout(400); pg.keyboard.press('Enter')
    J(pg,"()=>{ startMission(MISSIONS.find(m=>m.id==='hold-kappa')); }"); pg.wait_for_timeout(300); pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    J(pg,"()=>{ if(ui.mode==='pause') pause(false); __hc.G.paused=false; }"); pg.wait_for_timeout(200)
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-angle=swiftshader','--enable-unsafe-swiftshader']); pg=b.new_page(viewport={'width':1366,'height':800})
    pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: m.type=='error' and 'ERR_' not in m.text and errs.append(m.text))
    pg.goto('file:///home/claude/hollow_colony/index.html'); J(pg,"()=>{ localStorage.removeItem('hc-zoom'); localStorage.removeItem('hc-dist3d'); localStorage.removeItem('hc-view3d'); }")
    start(pg)
    J(pg,"()=>{ ui.follow=false; __hc.G.following=false; const u=__hc.G.ents.find(e=>!e.dead&&e.kind==='unit'&&e.faction==='corps'); centerOn(u.x,u.y); }")
    c0=J(pg,"()=>viewCenter()")
    check('starts at normal height', J(pg,"()=>zoom2()")==1)
    pg.screenshot(path='/home/claude/zoom-1.png')
    for _ in range(5): pg.keyboard.press('-')
    z=J(pg,"()=>zoom2()"); c1=J(pg,"()=>viewCenter()")
    check('minus goes higher up', abs(z-0.5)<0.01, z)
    check('a map smaller than the view sits in the middle', abs(J(pg,"()=>__hc.G.cam.x+viewW()/2")-J(pg,"()=>__hc.G.map.w*TILE/2"))<2)
    check('more map in view', abs(J(pg,"()=>viewW()")-1366*2)<1)
    pg.wait_for_timeout(300); pg.screenshot(path='/home/claude/zoom-05.png')
    # the mouse still finds the soldier under it
    r=J(pg,"()=>{ const u=__hc.G.ents.find(e=>!e.dead&&e.kind==='unit'&&e.faction==='corps'); const z=zoom2(), sx=(u.x-__hc.G.cam.x)*z, sy=(u.y-__hc.G.cam.y)*z; const w=toWorld(sx,sy); return Math.hypot(w.x-u.x,w.y-u.y); }")
    check('screen → map at height', r<2, r)
    check('saved', J(pg,"()=>JSON.parse(localStorage.getItem('hc-zoom'))")==0.5)
    for _ in range(10): pg.keyboard.press('+')
    check('plus comes down, capped', abs(J(pg,"()=>zoom2()")-1.5)<0.01, J(pg,"()=>zoom2()"))
    pg.wait_for_timeout(200); pg.screenshot(path='/home/claude/zoom-15.png')
    J(pg,"()=>centerOn(__hc.G.map.w*TILE/2,__hc.G.map.h*TILE/2)"); c0=J(pg,"()=>viewCenter()"); pg.keyboard.press('-'); c1=J(pg,"()=>viewCenter()")
    check('the middle stays put', abs(c1['x']-c0['x'])<2 and abs(c1['y']-c0['y'])<2, [c0,c1])
    pg.keyboard.press('0')
    check('0 resets', J(pg,"()=>zoom2()")==1)
    pg.click('#btn-cam-up'); check('top bar − goes higher', J(pg,"()=>zoom2()")<1)
    pg.click('#btn-cam-down'); check('top bar + comes back', abs(J(pg,"()=>zoom2()")-1)<1e-9)
    pg.keyboard.press('NumpadSubtract'); check('numpad minus', J(pg,"()=>zoom2()")<1)
    pg.keyboard.press('-'); pg.keyboard.press('-')
    zs=J(pg,"()=>ui.zoom")
    # reload: the height is remembered
    start(pg)
    check('remembered after reload', abs(J(pg,"()=>zoom2()")-zs)<1e-6, [zs, J(pg,"()=>zoom2()")])
    # 3D: same spot in the middle on switching, + and − change the distance, saved
    cA=J(pg,"()=>viewCenter()")
    pg.keyboard.press('F3'); pg.wait_for_timeout(1200)
    check('3D on', J(pg,"()=>v3Active()"))
    cB=J(pg,"()=>viewCenter()")
    check('switching keeps the middle', abs(cA['x']-cB['x'])<3 and abs(cA['y']-cB['y'])<3, [cA,cB])
    d0=J(pg,"()=>VIEW3D.dist"); pg.keyboard.press('-'); pg.keyboard.press('-'); d1=J(pg,"()=>VIEW3D.dist")
    check('3D minus goes higher', d1>d0, [d0,d1])
    pg.click('#btn-cam-up'); check('3D top bar − goes higher', J(pg,"()=>VIEW3D.dist")>d1); pg.click('#btn-cam-down')
    pg.keyboard.press('+'); check('3D plus comes down', J(pg,"()=>VIEW3D.dist")<d1)
    for _ in range(20): pg.keyboard.press('-')
    check('3D capped at maxDist', J(pg,"()=>VIEW3D.dist")==J(pg,"()=>VIEW3D.maxDist"))
    pg.wait_for_timeout(300); pg.screenshot(path='/home/claude/zoom-3d.png')
    check('3D saved', J(pg,"()=>JSON.parse(localStorage.getItem('hc-dist3d'))")==J(pg,"()=>VIEW3D.maxDist"))
    check('2D height untouched by 3D keys', abs(J(pg,"()=>ui.zoom")-zs)<1e-6)
    pg.keyboard.press('F3'); pg.wait_for_timeout(300)
    check('back in 2D at its own height', abs(J(pg,"()=>zoom2()")-zs)<1e-6)
    pg.goto('file:///home/claude/hollow_colony/index.html'); pg.wait_for_timeout(500)
    check('3D distance loaded at boot', J(pg,"()=>VIEW3D.dist")==J(pg,"()=>VIEW3D.maxDist"))
    J(pg,"()=>{ localStorage.removeItem('hc-zoom'); localStorage.removeItem('hc-dist3d'); localStorage.removeItem('hc-view3d'); }")
    check('no errors', not errs, errs[:3])
    b.close()
print('ALL OK' if ok else 'SOME FAILED')
